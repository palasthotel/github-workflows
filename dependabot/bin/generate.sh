#!/usr/bin/env bash
# Writes the .github/dependabot.yml of a repository from the shared template: one
# entry per ecosystem the repository has, each with the same schedule, cooldown and
# groups. Dependabot can't extend a shared config, so every repository carries the
# whole file - generated here, so they don't drift apart. See docs/dependabot.md.
#
# Usage: generate.sh [REPO_DIR] [OUTPUT]
#   REPO_DIR   the repository                      (default: .)
#   OUTPUT     where to write, - for stdout        (default: REPO_DIR/.github/dependabot.yml)
#   ASSIGNEE   who gets the pull requests          (default: JanaME)
#
# What it finds, outside node_modules/, vendor/ and build/:
#   npm             every directory with a package-lock.json
#   composer        every directory with a composer.json that requires a package -
#                   php, ext-* and the like aren't packages, and a composer.json that
#                   only sets up the autoloader has nothing to update
#   github-actions  always
set -euo pipefail

die() {
  echo "ERROR: $*" >&2
  exit 1
}

REPO_DIR="$(cd "${1:-.}" && pwd)" || die "${1:-.} does not exist"
OUTPUT="${2:-$REPO_DIR/.github/dependabot.yml}"
ASSIGNEE="${ASSIGNEE:-JanaME}"
command -v jq >/dev/null || die "jq is not installed"

# Directories holding FILE, as Dependabot wants them: "/" or "/sub/dir", sorted.
find_dirs() {
  (cd "$REPO_DIR" && find . \( -name node_modules -o -name vendor -o -name build -o -name .git \) -prune \
    -o -name "$1" -type f -print) \
    | sed -E "s#^\./##; s#/?$1\$##; s#^#/#" | sort
}

NPM_DIRS=()
while IFS= read -r dir; do NPM_DIRS+=("$dir"); done < <(find_dirs package-lock.json)

COMPOSER_DIRS=()
while IFS= read -r dir; do
  if jq -e '[(.require // {}), (."require-dev" // {})] | add | keys
      | map(select(test("^(php|php-64bit|hhvm|ext-.*|lib-.*|composer|composer-plugin-api|composer-runtime-api)$") | not))
      | length > 0' "$REPO_DIR${dir%/}/composer.json" >/dev/null; then
    COMPOSER_DIRS+=("$dir")
  fi
done < <(find_dirs composer.json)

# entry ECOSYSTEM DIR...: the settings every entry shares
entry() {
  local ecosystem="$1" dir
  shift
  echo
  echo "  - package-ecosystem: \"$ecosystem\""
  if [[ $# -eq 1 ]]; then
    echo "    directory: \"$1\""
  else
    echo "    directories:"
    for dir in "$@"; do echo "      - \"$dir\""; done
  fi
  cat <<YAML
    schedule:
      interval: "weekly"
      day: "monday"
      time: "07:00"
      timezone: "Europe/Berlin"
    assignees:
      - "$ASSIGNEE"
    commit-message:
      prefix: "deps"
      include: "scope"
    open-pull-requests-limit: 10
YAML
}

# cooldown PATTERN: 7 days for a new release before Dependabot proposes it - except our
# own packages. Security updates come right away: Dependabot applies no cooldown to them.
cooldown() {
  cat <<YAML
    cooldown:
      default-days: 7
      exclude:
        - "$1"
YAML
}

generate() {
  cat <<'YAML'
---
# Generated by palasthotel/github-workflows (dependabot/bin/generate.sh). Change the
# template there and regenerate, not this file - the PR checks warn when it differs.
# See https://github.com/palasthotel/github-workflows/blob/main/docs/dependabot.md
version: 2

updates:
YAML

  if [[ ${#NPM_DIRS[@]} -gt 0 ]]; then
    entry npm "${NPM_DIRS[@]}"
    cooldown "@palasthotel/*"
    cat <<'YAML'
    groups:
      # The @wordpress packages are released together and depend on each other: one
      # pull request for all of them, major versions included.
      wordpress:
        patterns:
          - "@wordpress/*"
          - "@types/wordpress__*"
      # Everything else without a major step. A major version gets a pull request of
      # its own, so it is built and looked at alone.
      npm:
        patterns:
          - "*"
        update-types:
          - "minor"
          - "patch"
      npm-security:
        applies-to: "security-updates"
        patterns:
          - "*"
YAML
  fi

  if [[ ${#COMPOSER_DIRS[@]} -gt 0 ]]; then
    entry composer "${COMPOSER_DIRS[@]}"
    cooldown "palasthotel/*"
    cat <<'YAML'
    groups:
      composer:
        patterns:
          - "*"
        update-types:
          - "minor"
          - "patch"
      composer-security:
        applies-to: "security-updates"
        patterns:
          - "*"
YAML
  fi

  # "/" makes Dependabot read .github/workflows. A path like /.github/ is taken for the
  # location of a composite action, and the workflows are never checked.
  entry github-actions "/"
  cooldown "palasthotel/*"
  cat <<'YAML'
    groups:
      github-actions:
        patterns:
          - "*"
YAML
}

if [[ "$OUTPUT" == "-" ]]; then
  generate
else
  mkdir -p "$(dirname "$OUTPUT")"
  generate > "$OUTPUT"
  echo "${OUTPUT#"$REPO_DIR/"}: npm ${NPM_DIRS[*]:-none}, composer ${COMPOSER_DIRS[*]:-none}, github-actions /"
fi
